/**
 * Order & Booking Type Definitions for SwiftDrop
 * Member 06 - Customer UI & Booking Experience
 */

export type ParcelSize = 'SMALL' | 'MEDIUM' | 'LARGE' | 'EXTRA_LARGE';

export type OrderStatus =
  | 'Created'
  | 'Picked Up'
  | 'In Transit'
  | 'Out for Delivery'
  | 'Delivered'
  | 'Failed'
  | string;

/**
 * Request payload sent to POST /api/v1/orders/quote
 * Used to get an official price estimate before confirming a booking.
 */
export interface OrderQuoteRequest {
  /** Town codes from GET /api/v1/orders/cities (e.g. COLOMBO, KANDY). */
  pickupCity: string;
  dropoffCity: string;
  weightKg: number;
  parcelSize: ParcelSize;
}

/**
 * A supported pickup / delivery town returned by GET /api/v1/orders/cities.
 */
export interface CityOption {
  code: string;
  name: string;
  district?: string;
}

/**
 * Response received from POST /api/v1/orders/quote
 */
export interface OrderQuoteResponse {
  estimatedFee: number;
  currency: string;
  estimatedDistanceKm?: number;
  breakdown?: {
    baseFee: number;
    weightFee: number;
    distanceFee?: number;
    zoneSurcharge?: number;
    totalFee?: number;
    currency?: string;
  };
}

/**
 * Request payload sent to POST /api/v1/orders
 * Used to officially create the delivery order in the backend database.
 */
export interface CreateOrderRequest {
  pickupAddress: string;
  pickupContactName: string;
  pickupContactPhone: string;
  dropoffAddress: string;
  dropoffContactName: string;
  dropoffContactPhone: string;
  parcelDescription: string;
  parcelSize: ParcelSize;
  weightKg: number;
  deliveryInstructions?: string;
  /** Town codes from GET /api/v1/orders/cities. */
  pickupCity: string;
  dropoffCity: string;
  /** The fee the customer saw in the quote; a different current fee is rejected with 409. */
  expectedFee?: number;
}

/**
 * Response received from POST /api/v1/orders
 * Contains the authoritative tracking number generated by the Order Service.
 */
export interface CreateOrderResponse {
  id: number | string;
  trackingNumber: string;
  status: OrderStatus;
  deliveryFee: number;
  currency: string;
  pickupAddress: string;
  dropoffAddress: string;
  createdAt: string;
  message?: string;
}

/**
 * How an order's delivery fee was calculated (as stored when the order was placed).
 * baseFee + weightFee + distanceFee + zoneSurcharge = totalFee.
 */
export interface FeeBreakdown {
  baseFee: number;
  weightFee: number;
  distanceFee: number;
  zoneSurcharge: number;
  totalFee: number;
  currency?: string;
}

/**
 * Full Delivery Order representation returned by:
 * GET /api/v1/orders (List)
 * GET /api/v1/orders/{id} (Single Order Details - Authenticated/Private)
 */
export interface DeliveryOrder {
  id: number | string;
  trackingNumber: string;
  status: OrderStatus;
  deliveryFee: number;
  currency: string;
  pickupAddress: string;
  pickupContactName?: string;
  pickupContactPhone?: string;
  dropoffAddress: string;
  dropoffContactName?: string;
  dropoffContactPhone?: string;
  parcelDescription?: string;
  parcelSize?: ParcelSize;
  weightKg?: number;
  deliveryInstructions?: string;
  createdAt: string;
  updatedAt?: string;
  courierName?: string;
  courierVehicle?: string;
  courierPhone?: string;
  branch?: string;
  distanceKm?: number;
  /** How the delivery fee was calculated; absent on records that do not carry it. */
  feeBreakdown?: FeeBreakdown;
}

/**
 * Milestone event in a parcel's public delivery lifecycle
 */
export interface PublicTrackingEvent {
  status: OrderStatus;
  timestamp?: string;
  location?: string;
  description?: string;
}

/**
 * Safe Public Tracking Response:
 * GET /api/v1/tracking/{trackingNumber}
 * Contains only safe public data — NO private phone numbers, emails, or internal IDs.
 */
export interface PublicTrackingResponse {
  trackingNumber: string;
  status: OrderStatus;
  origin?: string;
  destination?: string;
  parcelCategory?: string;
  estimatedDelivery?: string;
  events?: PublicTrackingEvent[];
  updatedAt?: string;
  courierName?: string;
  courierPhone?: string;
  branch?: string;
  distanceKm?: number;
}
